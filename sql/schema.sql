CREATE DATABASE IF NOT EXISTS seguridad CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
USE seguridad;

CREATE TABLE IF NOT EXISTS lecturas (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    movimiento TINYINT,
    distancia FLOAT,
    estado VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS eventos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    tipo VARCHAR(20),
    sensor VARCHAR(20)
);

CREATE TABLE IF NOT EXISTS comandos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    fecha DATETIME DEFAULT CURRENT_TIMESTAMP,
    accion VARCHAR(20),
    origen VARCHAR(20),
    resultado VARCHAR(20)
);
